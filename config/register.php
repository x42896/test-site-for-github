
<?php
// Подключениек к БД
require_once $_SERVER['DOCUMENT_ROOT'] . '/config/database.php'; // важно правильно указать путь
$stmt = $pdo->query("SELECT * FROM users"); // важно правильно указать название таблицы




// Получаем данные из формы и удаляем лишние пробелы (то что вводит пользователь)
// Если поля userName нет — переменная станет пустой строкой (скрипт продолжит работу) else сокращённое
$userName = trim($_POST['user-name'] ?? '');
$userEmail = trim($_POST['user-email'] ?? '');
$userPassword = $_POST['user-password'] ?? '';


// Простейшая валидация: проверяем, что все поля заполнены
if (empty($userName) || empty($userEmail) || empty($userPassword)) {
    die("Заполните все поля!");
}


// Проверка корректности userEmail с помощью встроенной фильтрации
if (!filter_var($userEmail, FILTER_VALIDATE_EMAIL)) {
    die("Вы ввели некорректный email адрес!");
}

// Проверка пароля
if (strlen($userPassword) < 6) {
    die("Пароль должен содержать минимум 6 символов!");
}


// Хеширование пароля перед сохранением в базу (безопасная практика)
$hashedPassword = password_hash($userPassword, PASSWORD_DEFAULT);


// Подготавливаем SQL-запрос для добавления пользователя и начисление 1000 бонусов
// $sql — это как "шаблон письма" для базы данных
// Добавь нового пользователя с этими данными и дай ему 1000 бонусов
$sql = "INSERT INTO users (username, email, password, balance)
       VALUES (:username, :email, :password, 1000)";
// $stmt = $pdo->prepare($sql) — "Подготовь конверт и надпиши адреса
$stmt = $pdo->prepare($sql);



// Данные для подготовленного sql запроса
try {
    // Выполняем подготовленный запрос, передавая параметры, "Вложи в конверт реальные данные и отправь"
    $stmt->execute([
        ':username' => $userName,
        ':email' => $userEmail,
        ':password' => $hashedPassword
    ]);

    // Если всё успешно — информируем пользователя и предлагаем перейти на страницу входа
    echo "Регистрация успешна! Вам начислено 1000 бонусов.";
    echo '<br><a href="/php/login-page.php">Войти в личный кабинет</a>';


    // try-catch — Попробуй отправить, а если почтальон вернётся с ошибкой — обработай её
} catch (PDOException $e) {
    // Обрабатываем ошибки
    // Код 23000 обычно означает нарушение уникального ограничения (например, duplicate userEmail)
    if ($e->getCode() == 23000) {
        echo "Пользователь с таким email уже зарегистрирован.";
    } else {
        // Для других ошибок (лучше не показывать детали пользователю)
        // В продакшене лучше логировать ошибку, а пользователю показывать нейтральное сообщение.
        echo "Ошибка регистрации: " . $e->getMessage(); // это для простосты и чтобы сразу видно было ошибку
        // Если для себя создавать то расскоментировать 2 строчки ниже а строчку выше закоментировать
        // error_log("Ошибка регистрации: " . $e->getMessage()); // пишем в лог. Где смотреть логи – написал ниже
        // echo "Произошла техническая ошибка. Попробуйте позже."; // Показываем ошибку пользователю
    }
}
