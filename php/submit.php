<?php
// Получаем данные из формы и удаляем лишние пробелы
$name = trim($_POST['name']);
$age = trim($_POST['age']);
$course = trim($_POST['course']);



// Параметры подключения к БД
$host = 'localhost';    // Обычно localhost даже на хостинге
$dbname = 'school';     // Название базы данных
$user = 'root';         // на локальном сервере обычно root
$password = 'root';     // пароль может быть пустым на MAMP/XAMPP

// Подключение к БД
$conn = new mysqli($host, $user, $password, $dbname);
// Проверка подключения
if ($conn->connect_error) {
    die("Ошибка подключения: " . $conn->connect_error);
}






// SQL-запрос с плейсхолдерами (вопросительными знаками)
// Плейсхолдеры обозначают места, куда будут подставлены реальные значения
// Это защищает от SQL-инъекций, так как значения обрабатываются отдельно от структуры запроса
$sql = "INSERT INTO applications (name, age, course) VALUES (?, ?, ?)";

// Подготовка запроса
// MySQL заранее анализирует структуру запроса без значений, возвращает объект подготовленного выражения
// prepare() и bind_param() безопасный способ вставки (предотвращает SQL-инъекции)
$stmt = $conn->prepare($sql);

// Привязка параметров к подготовленному выражению
// Первый аргумент - строка типов параметров:
//   s - string (строка)
//   i - integer (целое число)
//   d - double (число с плавающей точкой)
//   b - blob (бинарные данные)
// Последующие аргументы - переменные, значения которых будут подставлены
$stmt->bind_param("sis", $name, $age, $course); // s - строка, i - число, s - строка

// Проверка успешности подготовки и выполнения запроса
// execute() — выполнение запроса
if ($stmt->execute()) {
    echo "Спасибо, заявка отправлена!";
} else {
    echo "Ошибка: " . $stmt->error;
}



// Закрываем подготовленный запрос
$stmt->close();
// Закрываем соединение
$conn->close();
?>